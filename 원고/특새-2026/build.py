# 특새 설교 모음 원고 합치기 (날짜별: 기도 제목 → 설교 요약 → 함께 전한 말씀 → 찬양)
import csv
from days import DAYS, DAY6
songs={}
for k,t in csv.reader(open('찬양목록.tsv'),delimiter='\t'): songs.setdefault(k,[]).append(t)

head='''책 제목: 제24차 가을 | 글로벌 특별새벽부흥회
글쓴이:
날짜: 2026.10.19(월)~24(토)
부제: 날마다의 말씀 · 기도 제목 · 찬양
표지 그림: https://webbook-kr.github.io/img/teukse-2026/banner.jpg
간격: 촘촘

## 특새 안내

**주제** ==여호와께 능치 못한 일이 있겠느냐?==
Is anything too hard for the Lord?

> 여호와께 능하지 못한 일이 있겠느냐 기한이 이를 때에 내가 네게로 돌아오리니 사라에게 아들이 있으리라 (창 18:14)

- **일정** 2026.10.19(월)~24(토) · 오전 4시 30분 (토 5시 30분)
- **장소** 사랑의교회 본당 및 각 예배실 · 인터넷 생중계
- **강사** 국내외 설교자 다섯 분과 해외 신학자·목회자 다섯 분, 마지막 날 오정현 담임목사

> 물이 바다를 덮음 같이 여호와의 영광을 인정하는 것이 세상에 가득함이니라 (합 2:14) — 오정현 목사 인사말 중

::: 사랑의교회 설교 영상·특새 뉴스레터·찬양 목록을 바탕으로 AI로 정리한 비공식 묵상 자료입니다. 정확한 말씀은 영상으로 확인해 주세요

## 날짜별 일정

| 날짜 | 말씀 · 설교자 |
| --- | --- |'''
rows=''.join(f"\n| {x['d']} | **{x['t']}**<br>{x['p']} · {x['g']['p']} |" for x in DAYS)
rows+=f"\n| {DAY6['d']} | **내 영혼의 풀 콘서트**<br>{DAY6['p']} |"
out=[head+rows+'\n\n::: 날마다 기도 제목 → 설교 요약 → 함께 전한 말씀 → 그날의 찬양 순서\n']

def prayer(x,short):
    s=f"## 오늘의 기도 제목 · {x['n']}\n\n머리글: {short} · 기도 제목\n\n핵심: {x['pray']}\n\n"
    s+='\n'.join(f"{i+1}. {t}" for i,t in enumerate(x['items']))+'\n'
    return s
for x in DAYS:
    short=x['d'].split('(')[0]
    out.append(f"# {x['d']} · {x['n']} | {x['t']} — {x['p']}\n\n"+prayer(x,short))
    out.append(open(x['f']).read().strip())
    g=x['g']
    s=f"## 함께 전한 말씀 · {g['p']}\n\n머리글: {short} · {g['p']}\n\nyoutube: {g['id']}\n\n발표자: {g['p']} | {g['org']} · {g['ref']}\n\n**{g['t']}**\n\n"
    s+='\n\n'.join('- '+p for p in g['pts'])
    if g['quote']: s+=f"\n\n> {g['quote']}"
    s+="\n\n::: 요약은 특새 뉴스레터 '강단 아카이브'와 '설교 어록'을 바탕으로 정리했습니다\n"
    out.append(s)
    L=songs.get(x['key'],[])
    out.append(f"## 오늘의 찬양 · {x['n']}\n\n머리글: {short} · 찬양\n\n**{x['d']} 새벽 · {len(L)}곡**\n\n"+'\n'.join(f"{i+1}. {t}" for i,t in enumerate(L))+'\n')
x=DAY6; short=x['d'].split('(')[0]
out.append(f"# {x['d']} · {x['n']} | 내 영혼의 풀 콘서트 — {x['p']}\n\n"+prayer(x,short))
out.append(f'''## 내 영혼의 풀 콘서트

머리글: {short} · 마지막 날

발표자: {x['p']} | {x['org']} · {x['ref']}

**{x['t']}**

- 한 주간 받은 새 마음과 새 영과 새 은혜를 ==높은 찬양==으로 올려 드리는 마지막 새벽 (오전 5시 30분)
- 깊은 말씀 · 높은 찬양 · 뜨거운 기도 — 이번 특새의 세 기둥을 한자리에
- 집회 후 개근 출석부를 '특새 동판'으로 교환, 사랑글로벌광장에서 '기쁨의 잔치'

> 내가 영으로 기도하고 또 마음으로 기도하며 내가 영으로 찬송하고 또 마음으로 찬송하리라 (고전 14:15)

::: 마지막 날 영상과 찬양 목록은 아직 공개되지 않아 싣지 못했습니다
''')
out.append('''## 엿새를 마치며

머리글:

- **첫째 날** 율법도 종교도 못 하는 것을 하나님이 하셨다 — ==이미 거룩하게 된 신분==
- **둘째 날** 기적이 없던 다윗의 동굴에 하나님이 찾아오셨다 — ==주는 나의 피난처==
- **셋째 날** 나라가 망해도 약속은 여호야긴의 배급표에 살아 있었다 — ==맡겨 볼 때 소망을 배운다==
- **넷째 날** 말과 병거를 끊고 하나님만 의지한 다윗 — ==내가 네 하나님 아니냐==
- **다섯째 날** 막힌 길은 믿음을 검증하는 하나님의 자리 — ==가만히, 그리고 한 걸음씩==
- **여섯째 날** 깊은 말씀, 높은 찬양, 뜨거운 기도 — ==내 영혼의 풀 콘서트==

핵심: 여호와께 능치 못한 일이 있겠느냐. 이번 특새에서 받은 은혜를 각자의 골방과 일터로 가져가십시오
''')
open('제24차-가을-글로벌-특별새벽부흥회.md','w').write('\n\n'.join(out))
print('ok')
