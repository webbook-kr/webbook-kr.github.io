def sheet(ks,name):
    ims=[Image.open(f'crop/{k}.jpg') for k in ks]; W=480
    th=[im.resize((W,int(im.height*W/im.width))) for im in ims]
    H=sum(t.height for t in th)+10*len(th)
    s=Image.new('RGB',(W,H),'#888'); y=0
    for t in th: s.paste(t,(0,y)); y+=t.height+10
    s.save(name,quality=75)
